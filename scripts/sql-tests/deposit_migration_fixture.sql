-- Minimal disposable PostgreSQL schema for exercising the deposit-credit migration.
-- This is a test fixture, not a replacement for the production Supabase schema.

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role NOLOGIN; END IF;
END;
$roles$;

CREATE TABLE public.platform_settings (
  key text PRIMARY KEY,
  value_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE public.users (
  id uuid PRIMARY KEY,
  current_platform_balance numeric(18,2) NOT NULL DEFAULT 0,
  principal_balance numeric(18,2) NOT NULL DEFAULT 0,
  first_deposit_done boolean NOT NULL DEFAULT false,
  selected_tier_id text,
  referred_by uuid,
  profit_balance numeric(18,2) NOT NULL DEFAULT 0
);

CREATE TABLE public.vip_tiers (
  id text PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE public.deposit_submissions (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL,
  tier_id text NOT NULL,
  gross_amount numeric(18,2) NOT NULL,
  deposit_fee numeric(18,2) NOT NULL DEFAULT 0,
  credited_amount numeric(18,2),
  status text,
  ai_review_status text,
  txid text,
  network text,
  token_contract text,
  raw_amount text,
  sender_address text,
  block_timestamp timestamptz,
  verification_source text,
  verified_at timestamptz,
  verification_note text
);

CREATE TABLE public.referrals (
  user_id uuid NOT NULL,
  referred_user_id uuid NOT NULL,
  referral_level integer NOT NULL,
  platform_reward numeric(18,2) NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE public.account_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  entry_type text NOT NULL,
  amount numeric(18,2) NOT NULL,
  description text NOT NULL,
  reference_id text,
  metadata jsonb
);

CREATE TABLE public.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid,
  target_user_id uuid,
  event_type text NOT NULL,
  description text NOT NULL,
  reference_id text
);

