-- Disposable schema for manual balance adjustment regression tests only.
CREATE TABLE public.users (
  id uuid PRIMARY KEY,
  role text NOT NULL,
  status text NOT NULL,
  current_platform_balance numeric(18,2) NOT NULL DEFAULT 0,
  manual_credit_balance numeric(18,2) NOT NULL DEFAULT 0,
  withdrawal_held numeric(18,2) NOT NULL DEFAULT 0
);
CREATE TABLE public.admin_adjustments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  admin_user_id uuid NOT NULL,
  adjustment_type text NOT NULL,
  amount numeric(18,2) NOT NULL CHECK (amount > 0),
  reason text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.account_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  entry_type text NOT NULL,
  amount numeric(18,2) NOT NULL,
  description text NOT NULL,
  actor_user_id uuid,
  reference_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS text LANGUAGE sql STABLE
AS $fn$ SELECT current_setting('aegis.test_role', true) $fn$;
CREATE OR REPLACE FUNCTION public.current_app_user_id()
RETURNS uuid LANGUAGE sql STABLE
AS $fn$ SELECT NULLIF(current_setting('aegis.test_actor_id', true), '')::uuid $fn$;

