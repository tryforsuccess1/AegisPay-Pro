-- Disposable schema for the withdrawal decision + ledger migration integration test.
-- Test only: do not copy this simplified schema over Supabase production.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE TABLE public.users (
  id uuid PRIMARY KEY,
  role text NOT NULL,
  status text NOT NULL DEFAULT 'Active',
  current_platform_balance numeric(18,2) NOT NULL DEFAULT 0,
  withdrawal_held numeric(18,2) NOT NULL DEFAULT 0
);
CREATE TABLE public.withdrawal_requests (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL,
  amount numeric(18,2) NOT NULL,
  destination_address text NOT NULL DEFAULT 'TTestDestinationAddress',
  ai_risk_score numeric(6,4) NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'PENDING_APPROVAL',
  created_at timestamptz NOT NULL DEFAULT now(),
  approval_date timestamptz,
  approved_by uuid,
  fee_amount numeric(18,2) NOT NULL DEFAULT 0,
  net_amount numeric(18,2) NOT NULL DEFAULT 0,
  telegram_status text NOT NULL DEFAULT 'PREPARED',
  payout_txid text,
  payout_started_at timestamptz,
  payout_completed_at timestamptz,
  payout_error text,
  panel_decision text NOT NULL DEFAULT 'PENDING',
  panel_decided_at timestamptz,
  telegram_decision text NOT NULL DEFAULT 'PENDING',
  telegram_approver_id text,
  telegram_decided_at timestamptz,
  telegram_message_id text,
  balance_deducted boolean NOT NULL DEFAULT false,
  ai_decision text NOT NULL DEFAULT 'PENDING_REVIEW',
  ai_confidence numeric,
  ai_review_reason text,
  ai_reviewed_at timestamptz
);
CREATE TABLE public.account_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  actor_user_id uuid,
  entry_type text NOT NULL,
  amount numeric(18,2) NOT NULL DEFAULT 0,
  description text NOT NULL,
  reference_id text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid,
  target_user_id uuid,
  event_type text NOT NULL,
  description text NOT NULL,
  reference_id text
);

CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS text LANGUAGE sql STABLE
AS $fn$ SELECT current_setting('aegis.test_role', true) $fn$;
CREATE OR REPLACE FUNCTION public.current_app_user_id()
RETURNS uuid LANGUAGE sql STABLE
AS $fn$ SELECT NULLIF(current_setting('aegis.test_actor_id', true), '')::uuid $fn$;

